// Builds the Android buffer editor page: bundles main.ts with esbuild, inlines
// it into page.html and writes one TypeScript module holding the HTML string.
// Run with `npm run build:buffer-editor`; the output is committed so a fresh
// clone and CI need no build step.
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(
  here,
  '../../src/interface/components/buffer/android/web-editor-html.generated.ts'
);

const result = await build({
  entryPoints: [join(here, 'main.ts')],
  bundle: true,
  minify: true,
  format: 'iife',
  target: ['chrome100'],
  write: false,
  legalComments: 'none',
});

const script = result.outputFiles[0].text.replaceAll('</script', '<\\/script');
const page = (await readFile(join(here, 'page.html'), 'utf8')).replace(
  '/*BUNDLE*/',
  () => script
);

await writeFile(
  out,
  `// Generated by tools/buffer-web-editor/build.mjs (npm run build:buffer-editor). Do not edit.\n` +
    `export const BUFFER_WEB_EDITOR_HTML = ${JSON.stringify(page)};\n`
);
console.log(`wrote ${out} (${page.length} bytes)`);
